const DB = {};
for (const style of Object.keys(RAW)) {
  DB[style] = RAW[style].map((r, i) => ({ id: i + 1, title: r[0], meta: r[1], tag: r[2], variant: r[3] }));
}

const server = http.createServer((req, res) => {
  const parsed = url.parse(req.url, true);
  if (parsed.pathname !== '/api/items') {
    res.writeHead(404, { 'Content-Type': 'application/json; charset=utf-8' });
    res.end(JSON.stringify({ code: 404, message: 'not found' }));
    return;
  }
  const style = String(parsed.query.style || 'constructivism');
  const page = Math.max(1, parseInt(parsed.query.page, 10) || 1);
  const pageSize = Math.min(20, Math.max(1, parseInt(parsed.query.pageSize, 10) || 6));
  const all = DB[style] || [];
  const start = (page - 1) * pageSize;
  const list = all.slice(start, start + pageSize);

  // 模拟网络延迟，方便观察加载态
  const latency = 300 + Math.floor(Math.random() * 300);
  setTimeout(() => {
    res.writeHead(200, { 'Content-Type': 'application/json; charset=utf-8' });
    res.end(JSON.stringify({
      code: 0,
      message: 'ok',
      data: { list, page, pageSize, total: all.length, hasMore: start + list.length < all.length },
    }));
  }, latency);
});

const PORT = 3000;
server.listen(PORT, () => {
  console.log(`风格样张 mock 服务器已启动: http://127.0.0.1:${PORT}`);
  console.log('示例: http://127.0.0.1:3000/api/items?style=dadaism&page=1&pageSize=6');
});
